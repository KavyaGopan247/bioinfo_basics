#!/usr/bin/env bash

# ============================================================
# file_processing.sh
# ============================================================
# Bioinformatics-oriented text processing with standard Unix
# tools.
#
# Tools:
#   grep, awk, sed, cut, sort, uniq, tr, paste, join, wc
#
# Focus:
#   FASTA / FASTQ / VCF / BED / GTF
#   metadata extraction
#   filtering
#   counting
#   summarization
#   coordinate-based inspection
#
# All paths are generic and contain no confidential information.
# ============================================================

set -euo pipefail


# ============================================================
# 1. FASTA
# ============================================================

FASTA="data/reference.fasta"


# ------------------------------------------------------------
# Number of sequences
# ------------------------------------------------------------

grep -c '^>' "$FASTA"


# ------------------------------------------------------------
# Extract FASTA headers
# ------------------------------------------------------------

grep '^>' "$FASTA"


# ------------------------------------------------------------
# Extract sequence IDs only
# ------------------------------------------------------------

grep '^>' "$FASTA" |
    sed 's/^>//' |
    awk '{print $1}'


# ------------------------------------------------------------
# Count sequences by header pattern
# ------------------------------------------------------------

grep '^>chr' "$FASTA" | wc -l


# ------------------------------------------------------------
# Remove FASTA headers
# ------------------------------------------------------------

grep -v '^>' "$FASTA"


# ------------------------------------------------------------
# Count total sequence characters
# ------------------------------------------------------------

grep -v '^>' "$FASTA" |
    tr -d '\n' |
    wc -c


# ------------------------------------------------------------
# Calculate base composition
# ------------------------------------------------------------

grep -v '^>' "$FASTA" |
    tr -d '\n' |
    tr '[:lower:]' '[:upper:]' |
    fold -w1 |
    sort |
    uniq -c


# ------------------------------------------------------------
# Extract chromosome/reference names
# ------------------------------------------------------------

grep '^>' "$FASTA" |
    sed 's/^>//' |
    awk '{print $1}' |
    sort


# ============================================================
# 2. FASTQ
# ============================================================

FASTQ="data/sample.fastq"


# ------------------------------------------------------------
# Number of reads
# ------------------------------------------------------------

wc -l < "$FASTQ" |
    awk '{print "Reads:", $1/4}'


# ------------------------------------------------------------
# FASTQ headers
# ------------------------------------------------------------

awk 'NR % 4 == 1' "$FASTQ" |
    head


# ------------------------------------------------------------
# Extract read IDs
# ------------------------------------------------------------

awk 'NR % 4 == 1 {
    sub(/^@/, "")
    print $1
}' "$FASTQ" |
    head


# ------------------------------------------------------------
# Extract sequences
# ------------------------------------------------------------

awk 'NR % 4 == 2' "$FASTQ" |
    head


# ------------------------------------------------------------
# Extract quality strings
# ------------------------------------------------------------

awk 'NR % 4 == 0' "$FASTQ" |
    head


# ------------------------------------------------------------
# Read length distribution
# ------------------------------------------------------------

awk '
NR % 4 == 2 {
    print length($0)
}' "$FASTQ" |
    sort -n |
    uniq -c


# ------------------------------------------------------------
# Unique read lengths
# ------------------------------------------------------------

awk '
NR % 4 == 2 {
    print length($0)
}' "$FASTQ" |
    sort -n |
    uniq


# ------------------------------------------------------------
# GC-containing reads
# ------------------------------------------------------------

awk '
NR % 4 == 2 &&
($0 ~ /G/ || $0 ~ /C/)
' "$FASTQ" |
    wc -l


# ------------------------------------------------------------
# Reads containing N
# ------------------------------------------------------------

awk '
NR % 4 == 2 &&
$0 ~ /N/
' "$FASTQ" |
    wc -l


# ============================================================
# 3. FASTQ QUALITY
# ============================================================

# Extract quality strings

awk 'NR % 4 == 0' "$FASTQ" |
    head


# ------------------------------------------------------------
# Quality-string lengths
# ------------------------------------------------------------

awk '
NR % 4 == 0 {
    print length($0)
}' "$FASTQ" |
    sort -n |
    uniq -c


# ------------------------------------------------------------
# Identify reads with unusually short sequences
# ------------------------------------------------------------

awk '
NR % 4 == 2 &&
length($0) < 100 {
    print "Short read:", NR/4
}' "$FASTQ"


# ============================================================
# 4. VCF
# ============================================================

VCF="data/variants.vcf"


# ------------------------------------------------------------
# Show VCF header
# ------------------------------------------------------------

grep '^#' "$VCF"


# ------------------------------------------------------------
# Show column header
# ------------------------------------------------------------

grep '^#CHROM' "$VCF"


# ------------------------------------------------------------
# Remove headers
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    head


# ------------------------------------------------------------
# Number of variants
# ------------------------------------------------------------

grep -vc '^#' "$VCF"


# ------------------------------------------------------------
# Variants by chromosome
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    cut -f1 |
    sort |
    uniq -c


# ------------------------------------------------------------
# Variants by FILTER status
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    cut -f7 |
    sort |
    uniq -c


# ------------------------------------------------------------
# PASS variants
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    awk '$7 == "PASS"' |
    wc -l


# ------------------------------------------------------------
# SNP candidates
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    awk '
    length($4) == 1 &&
    length($5) == 1
    '


# ------------------------------------------------------------
# Indel candidates
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    awk '
    length($4) != length($5)
    '


# ------------------------------------------------------------
# Variant positions
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    cut -f1,2 |
    head


# ------------------------------------------------------------
# QUAL distribution
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    awk '{print $6}' |
    sort -n |
    head


# ============================================================
# 5. VCF GENOTYPE FIELDS
# ============================================================

# Extract sample columns

grep '^#CHROM' "$VCF" |
    cut -f10-


# ------------------------------------------------------------
# Extract genotype field
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    cut -f10 |
    cut -d':' -f1 |
    sort |
    uniq -c


# ------------------------------------------------------------
# Homozygous reference
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    cut -f10 |
    cut -d':' -f1 |
    grep -c '^0/0$'


# ------------------------------------------------------------
# Heterozygous
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    cut -f10 |
    cut -d':' -f1 |
    grep -c -E '^(0/1|1/0)$'


# ------------------------------------------------------------
# Homozygous alternate
# ------------------------------------------------------------

grep -v '^#' "$VCF" |
    cut -f10 |
    cut -d':' -f1 |
    grep -c '^1/1$'


# ============================================================
# 6. BED
# ============================================================

BED="data/regions.bed"


# ------------------------------------------------------------
# Inspect BED
# ------------------------------------------------------------

head "$BED"


# ------------------------------------------------------------
# Number of intervals
# ------------------------------------------------------------

wc -l < "$BED"


# ------------------------------------------------------------
# Intervals by chromosome
# ------------------------------------------------------------

cut -f1 "$BED" |
    sort |
    uniq -c


# ------------------------------------------------------------
# Sort BED by genomic coordinates
# ------------------------------------------------------------

sort -k1,1 -k2,2n "$BED" |
    head


# ------------------------------------------------------------
# Find intervals longer than 1 kb
# ------------------------------------------------------------

awk '
($3 - $2) > 1000
' "$BED"


# ------------------------------------------------------------
# Calculate interval lengths
# ------------------------------------------------------------

awk '
{
    print $1, $2, $3, $3-$2
}' OFS='\t' "$BED"


# ============================================================
# 7. GTF / GFF
# ============================================================

GTF="data/annotation.gtf"


# ------------------------------------------------------------
# Remove comments
# ------------------------------------------------------------

grep -v '^#' "$GTF" |
    head


# ------------------------------------------------------------
# Feature types
# ------------------------------------------------------------

grep -v '^#' "$GTF" |
    cut -f3 |
    sort |
    uniq -c


# ------------------------------------------------------------
# Count genes
# ------------------------------------------------------------

grep -v '^#' "$GTF" |
    awk '$3 == "gene"' |
    wc -l


# ------------------------------------------------------------
# Count transcripts
# ------------------------------------------------------------

grep -v '^#' "$GTF" |
    awk '$3 == "transcript"' |
    wc -l


# ------------------------------------------------------------
# Count exons
# ------------------------------------------------------------

grep -v '^#' "$GTF" |
    awk '$3 == "exon"' |
    wc -l


# ------------------------------------------------------------
# Genes by chromosome
# ------------------------------------------------------------

grep -v '^#' "$GTF" |
    awk '$3 == "gene" {print $1}' |
    sort |
    uniq -c


# ------------------------------------------------------------
# Positive / negative strand
# ------------------------------------------------------------

grep -v '^#' "$GTF" |
    cut -f7 |
    sort |
    uniq -c


# ============================================================
# 8. GTF ATTRIBUTE EXTRACTION
# ============================================================

# Extract gene_id attributes

grep -v '^#' "$GTF" |
    grep 'gene_id' |
    sed -n 's/.*gene_id "\([^"]*\)".*/\1/p' |
    head


# ------------------------------------------------------------
# Unique genes
# ------------------------------------------------------------

grep -v '^#' "$GTF" |
    sed -n 's/.*gene_id "\([^"]*\)".*/\1/p' |
    sort -u |
    wc -l


# ============================================================
# 9. GENERAL DATASET INSPECTION
# ============================================================

TABLE="data/metadata.tsv"


# Number of rows
wc -l "$TABLE"


# Number of columns
awk -F'\t' '
NR == 1 {
    print "Columns:", NF
}' "$TABLE"


# Display header
head -n 1 "$TABLE"


# Inspect first 10 records
head -n 11 "$TABLE"


# Inspect last 10 records
tail -n 10 "$TABLE"


# ============================================================
# 10. SORTING AND GROUPING
# ============================================================

# Sort a tab-separated table numerically by column 2

sort -t$'\t' -k2,2n "$TABLE"


# Sort descending

sort -t$'\t' -k2,2nr "$TABLE"


# Count unique values in column 2

cut -f2 "$TABLE" |
    sort |
    uniq -c


# ============================================================
# 11. FILTERING TABLES
# ============================================================

# Rows where column 3 equals PASS

awk -F'\t' '
NR == 1 || $3 == "PASS"
' "$TABLE"


# Rows where numeric column 4 > 30

awk -F'\t' '
NR == 1 || $4 > 30
' "$TABLE"


# Remove rows containing missing values

awk -F'\t' '
NR == 1 || $0 !~ /NA/
' "$TABLE"


# ============================================================
# 12. JOINING BIOLOGICAL TABLES
# ============================================================

# Example:
#
# sample_metadata.tsv
# sample_id    group
#
# qc_metrics.tsv
# sample_id    reads    mean_quality
#
# Both files must be sorted on sample_id.

sort -t$'\t' -k1,1 metadata.tsv > metadata.sorted.tsv
sort -t$'\t' -k1,1 qc_metrics.tsv > qc_metrics.sorted.tsv

join -t$'\t' \
    metadata.sorted.tsv \
    qc_metrics.sorted.tsv


# ============================================================
# 13. COMPARING FILE CONTENTS
# ============================================================

# IDs present in both files

comm -12 \
    <(sort ids_a.txt) \
    <(sort ids_b.txt)


# IDs only in A

comm -23 \
    <(sort ids_a.txt) \
    <(sort ids_b.txt)


# IDs only in B

comm -13 \
    <(sort ids_a.txt) \
    <(sort ids_b.txt)


# ============================================================
# 14. PIPELINE EXAMPLE
# ============================================================

# Example:
# Find PASS variants on a chromosome and summarize positions.

grep -v '^#' "$VCF" |
    awk '$1 == "chr1" && $7 == "PASS"' |
    cut -f2 |
    sort -n |
    tee results_chr1_pass_positions.txt |
    wc -l


# ============================================================
# 15. PRACTICAL CHECKS
# ============================================================

echo
echo "============================================"
echo "Bioinformatics file processing checks"
echo "============================================"

echo "FASTA sequences:"
grep -c '^>' "$FASTA"

echo
echo "FASTQ reads:"
awk 'END {print NR/4}' "$FASTQ"

echo
echo "VCF variants:"
grep -vc '^#' "$VCF"

echo
echo "BED intervals:"
wc -l < "$BED"

echo
echo "GTF genes:"
grep -v '^#' "$GTF" |
    awk '$3 == "gene"' |
    wc -l

echo
echo "============================================"
